"""Write a SystemVerilog wrapper that gives a synthesized hw/coproc block's
gate-level model its RTL struct ports back (block-synth.mk power flow).

Synthesis bit-blasts the wrapper top's struct ports into one port per bit,
named <port>_<bit>_ (yosys splitnets). This script reads those ports from the
gate-level model and emits

  module <name>(input clk_i, input rst_ni,
                input <type> <port>_i, ..., output <type> <port>_o, ...);

connecting bit k of each struct to <port>_<k>_. Each PORT=TYPE argument names
one struct port and its packed type; the direction follows the _i / _o
suffix. An initial check compares the bit counts with $bits() of the types,
so a layout change fails loudly.

Usage: block_glwrap.py GLSIM.v TOP NAME OUT.sv PORT=TYPE [PORT=TYPE ...]
  e.g. cvxif_req_i=cvxif_pkg::cvxif_req_t cvxif_resp_o=cvxif_pkg::cvxif_resp_t
"""

import re
import sys


def main(glsim, top, name, out, specs):
    types = {}
    for spec in specs:
        port, sep, typ = spec.partition("=")
        if not sep or not re.fullmatch(r"\w+_[io]", port) or not typ:
            sys.exit(f"block_glwrap: bad port spec {spec!r} (want PORT_i=TYPE or PORT_o=TYPE)")
        types[port] = typ
    if not types:
        sys.exit(__doc__)
    text = open(glsim).read()
    m = re.search(r"\bmodule\s+" + re.escape(top) + r"\s*\(([^;]*)\);", text)
    if not m:
        sys.exit(f"block_glwrap: module {top} not found in {glsim}")
    ports = [p.strip() for p in m.group(1).split(",")]
    bits = {p: [] for p in types}
    port_re = re.compile(r"(" + "|".join(map(re.escape, types)) + r")_(\d+)_")
    for p in ports:
        mm = port_re.fullmatch(p)
        if mm:
            bits[mm.group(1)].append(int(mm.group(2)))
        elif p not in ("clk_i", "rst_ni"):
            sys.exit(f"block_glwrap: unexpected port {p}")
    for k, v in bits.items():
        if not v or sorted(v) != list(range(len(v))):
            sys.exit(f"block_glwrap: {k} bits are not 0..{len(v) - 1}")
    decls = ["input  logic clk_i", "input  logic rst_ni"]
    decls += [f"{'input ' if p.endswith('_i') else 'output'} {t} {p}" for p, t in types.items()]
    checks = " ||\n        ".join(f"$bits({p}) != {len(bits[p])}" for p in types)
    conns = [".clk_i", ".rst_ni"]
    for p in types:
        conns += [f".{p}_{i}_({p}[{i}])" for i in range(len(bits[p]))]
    nl = chr(10)
    with open(out, "w") as fh:
        fh.write(f"""// Generated by target/ihp13/yosys/scripts/block_glwrap.py from {top}.
// Do not edit: regenerated with the gate-level model.
module {name} (
  {("," + nl + "  ").join(decls)}
);
  initial begin
    if ({checks})
      $fatal(1, "{name}: struct widths differ from the netlist's ports");
  end
  {top} i_netlist (
    {("," + nl + "    ").join(conns)}
  );
endmodule
""")


if __name__ == "__main__":
    if len(sys.argv) < 6:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4], sys.argv[5:])
