"""Write a SystemVerilog wrapper that gives a synthesized hw/coproc block's
gate-level model its RTL struct ports back (block-synth.mk power flow).

Synthesis bit-blasts the wrapper top's struct ports into one port per bit,
named <port>_<bit>_ (yosys splitnets). This script reads those ports from the
gate-level model and emits

  module <name>(input clk_i, input rst_ni,
                input cvxif_pkg::cvxif_req_t cvxif_req_i,
                output cvxif_pkg::cvxif_resp_t cvxif_resp_o);

connecting bit k of each struct to <port>_<k>_. An initial check compares the
bit counts with $bits() of the struct types, so a layout change fails loudly.

Usage: block_glwrap.py GLSIM.v TOP NAME OUT.sv
"""

import re
import sys


def main(glsim, top, name, out):
    text = open(glsim).read()
    m = re.search(r"\bmodule\s+" + re.escape(top) + r"\s*\(([^;]*)\);", text)
    if not m:
        sys.exit(f"block_glwrap: module {top} not found in {glsim}")
    ports = [p.strip() for p in m.group(1).split(",")]
    bits = {"cvxif_req_i": [], "cvxif_resp_o": []}
    for p in ports:
        mm = re.fullmatch(r"(cvxif_req_i|cvxif_resp_o)_(\d+)_", p)
        if mm:
            bits[mm.group(1)].append(int(mm.group(2)))
        elif p not in ("clk_i", "rst_ni"):
            sys.exit(f"block_glwrap: unexpected port {p}")
    for k, v in bits.items():
        if sorted(v) != list(range(len(v))):
            sys.exit(f"block_glwrap: {k} bits are not 0..{len(v) - 1}")
    conns = [".clk_i", ".rst_ni"]
    conns += [f".cvxif_req_i_{i}_(cvxif_req_i[{i}])" for i in range(len(bits["cvxif_req_i"]))]
    conns += [f".cvxif_resp_o_{i}_(cvxif_resp_o[{i}])" for i in range(len(bits["cvxif_resp_o"]))]
    with open(out, "w") as fh:
        fh.write(f"""// Generated by target/ihp13/yosys/scripts/block_glwrap.py from {top}.
// Do not edit: regenerated with the gate-level model.
module {name} (
  input  logic                   clk_i,
  input  logic                   rst_ni,
  input  cvxif_pkg::cvxif_req_t  cvxif_req_i,
  output cvxif_pkg::cvxif_resp_t cvxif_resp_o
);
  initial begin
    if ($bits(cvxif_req_i) != {len(bits['cvxif_req_i'])} ||
        $bits(cvxif_resp_o) != {len(bits['cvxif_resp_o'])})
      $fatal(1, "{name}: struct widths differ from the netlist's ports");
  end
  {top} i_netlist (
    {(","+chr(10)+"    ").join(conns)}
  );
endmodule
""")


if __name__ == "__main__":
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    main(*sys.argv[1:])
